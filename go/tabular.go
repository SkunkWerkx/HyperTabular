// Package hypertabular reads delimited text — CSV, TSV, any single-byte ASCII separator — and
// workbooks — XLSX, ODS and Numbers — a batch at a time into typed columns, with a HyperCast verdict
// for every cell.
//
// The core (libhypertabular's Rust, translated to Go) owns no memory and reads no files. It
// is handed a chunk of input and the buffers to fill, casts each plan column in one loop,
// and says how many rows it wrote and how far it got. Everything else is here: a
// DelimitedReader or a Sheet sizes the column buffers, the table that locates each cell and
// the arena for the rare text that is not in the input — once, reused for every batch. The
// core is called once per batch, not once per cell.
//
//   - One batch type. Read returns a *Batch — Rows, Columns, Line, Verdicts, a whole column
//     at a time (I32, F64, Text and the rest), and Get for any one cell — for delimited text
//     and for a sheet alike.
//   - Nothing is sniffed. The Dialect states the separator, the quoting, the header, what a read
//     passes over, how it takes a record of the wrong width, the encoding and the tokens that stand
//     for no value; SheetOptions states a sheet's header, its range and whether empty rows are
//     skipped; the plan states each column's door and, for numbers, its hypercast.NumFormat.
//     SuggestDelimited, SuggestDelimitedBytes and Sheet.Suggest say what a sample looks like, as a
//     plan to read and change, and no read takes one it wasn't handed.
//   - HyperCast is the judge. Fault, CastFailure, Detail, NumFormat, DateOptions, Decimal, Date,
//     CivilDateTime, Duration, UnixPrecision, DateOrder and ExcelEpoch are HyperCast's own types,
//     from its own module. A text cell means exactly what the HyperCast door of the same name would
//     say of the same text; a typed workbook cell is converted by the door directly.
//   - A bad value is a verdict; a broken file is an error. A cell that does not cast is a
//     fault in its column and the read goes on, and Batch.Faults lists a batch's. A record of the
//     wrong width, input that ends inside a quoted cell, a workbook whose container or parts cannot
//     be read, is a *Failure, returned after every intact row before it.
//   - Text is not copied out. A Text column's cells are slices of the input itself, or of a
//     workbook's shared strings; only a cell with "" inside, or a typed workbook cell said as
//     text, is written to an arena.
//
// The core is the crate built for wasm32-wasip1 and translated to Go source by wasm2go
// (internal/core, regenerated by `go generate`), as HyperCast's is: no cgo, no C compiler,
// nothing embedded, extracted or loaded at run time, and it builds wherever Go does — every
// GOOS and GOARCH, CGO_ENABLED=0, and TinyGo. Each reader runs in an instance of its own
// (core.go says what that costs and why).
package hypertabular

import (
	"unsafe"

	hypercast "github.com/SkunkWerkx/HyperCast/go"
	"github.com/google/uuid"
)

// NativeVersion reports the core's own version as "major.minor.patch" — read from the core
// itself, a literal compiled into the translated core from the crate's version, not from this
// module — so a deployment can confirm which core went into the binary. The core is compiled
// in, so there is nothing to load and the probe cannot fail.
func NativeVersion() string {
	return hypercast.FormatVersion(packedVersion())
}

// The core's return codes (rust/src/kernel/abi.rs), and the one core.go adds beside
// errGuestMemory.
const (
	codeOK       = 0
	errContract  = -1
	errStructure = -2
	errArena     = -3
	errCells     = -4
	errWindow    = -5
	errBatch     = -6
	errStateSize = -100 // the core's state block doesn't hold what this package mirrors, or won't fit
)

const contractViolation = "hypertabular: the core reported a contract violation — a binding bug, please report it"

// spanFlag is the top bit of a span's length. On a cell-table entry: the cell is quoted
// with "" inside and has to be unescaped to be read. On a Text value: the bytes are in the
// arena rather than in the input.
const spanFlag = 1 << 31

// The #[repr(C)] shapes that cross the ABI (rust/src/kernel/abi.rs), field for field: what
// core.go reads out of the core's memory, writes into it, or views it as.

type rawSpan struct {
	offset uint32
	len    uint32
}

func (s rawSpan) length() int   { return int(s.len &^ spanFlag) }
func (s rawSpan) flagged() bool { return s.len&spanFlag != 0 }

// ColumnSpec: the ordinal, the door, what the door declares, and HyperCast's RawNumFormat.
type rawSpec struct {
	ordinal uint32
	door    uint32
	param   uint32
	format  hypercast.RawNumFormat
}

// What a ColumnSpecWith adds to a ColumnSpec: date options (a Size of 0 declares none) and a month
// vocabulary, and the column's own tokens, each packed list in the core's shape.
type specExtra struct {
	date      hypercast.RawDateOptions
	months    string
	tokens    string
	hasTokens bool
	// The column's constraints, when checked says it declares them, and its enum list, packed as
	// the guest reads it.
	checked     bool
	constraints hypercast.RawConstraints
	enum        string
}

type rawFailure struct {
	code     uint32
	line     uint32
	record   uint64
	byte     uint64
	expected uint32
	found    uint32
}

type rawFilled struct {
	rows      uint64
	consumed  uint64
	arenaUsed uint64
	needed    uint64
	failure   rawFailure
}

// CellNote: what failed in a cell, and where its verdict came from. A notes array holds one a row.
type rawNote struct {
	detail uint16
	origin uint16
}

// RawProblem: one entry of hypertabular_faults' list, read back by decodeProblem.
type rawProblem struct {
	row        uint32
	planColumn uint32
	reason     uint32
	detail     uint16
	origin     uint16
	offset     uint32
	len        uint32
	expected   uint32
	found      uint32
	keyword    uint32
}

// rowLevel is a rawProblem's planColumn when the entry is about the row as a whole.
const rowLevel = 1<<32 - 1

// RawSuggestion: what hypertabular_suggest says of one column, read back by decodeSuggestion.
type rawSuggestion struct {
	door    uint32
	param   uint32
	status  uint32
	matched uint32
	sampled uint32
}

// RawTranscoded: how far hypertabular_transcode got, read back by decodeTranscoded.
type rawTranscoded struct {
	consumed  uint64
	written   uint64
	failureAt uint64
	failed    uint32
	_         uint32
}

// The core's state block (kernel::delimited::fill::State): where the input stands. The core
// writes it; this package reads the position out of it. Its size is checked against the
// core's own on every init (core.go's nativeInit).
type rawState struct {
	separator      uint8
	quoting        uint8
	skipBlankLines uint8
	engine         uint8
	line           uint32
	records        uint64
	offset         uint64
	expected       uint32
	started        uint8
	_              [3]uint8
	failure        rawFailure
}

// The layouts above held to the sizes the ABI gives them. Each pair of arrays compiles only
// when the two numbers are equal: one of the lengths is negative otherwise. The values the
// core writes are HyperCast's: its raw shapes, and its Decimal and Duration, which it lays
// out as the core does and checks itself.
type (
	_ [unsafe.Sizeof(rawSpan{}) - 8]struct{}
	_ [8 - unsafe.Sizeof(rawSpan{})]struct{}
	_ [unsafe.Sizeof(rawSpec{}) - 104]struct{}
	_ [104 - unsafe.Sizeof(rawSpec{})]struct{}
	_ [unsafe.Sizeof(rawFailure{}) - 32]struct{}
	_ [32 - unsafe.Sizeof(rawFailure{})]struct{}
	_ [unsafe.Sizeof(rawFilled{}) - 64]struct{}
	_ [64 - unsafe.Sizeof(rawFilled{})]struct{}
	_ [unsafe.Sizeof(rawState{}) - 64]struct{}
	_ [64 - unsafe.Sizeof(rawState{})]struct{}
	_ [unsafe.Sizeof(CellVerdict{}) - 12]struct{}
	_ [12 - unsafe.Sizeof(CellVerdict{})]struct{}
	_ [unsafe.Sizeof(rawNote{}) - 4]struct{}
	_ [4 - unsafe.Sizeof(rawNote{})]struct{}
	_ [unsafe.Sizeof(rawProblem{}) - 36]struct{}
	_ [36 - unsafe.Sizeof(rawProblem{})]struct{}
	_ [unsafe.Sizeof(rawSuggestion{}) - 20]struct{}
	_ [20 - unsafe.Sizeof(rawSuggestion{})]struct{}
	_ [unsafe.Sizeof(rawTranscoded{}) - 32]struct{}
	_ [32 - unsafe.Sizeof(rawTranscoded{})]struct{}
	// uuid.UUID is the sixteen bytes the core writes, in RFC 9562 order.
	_ [unsafe.Sizeof(uuid.UUID{}) - 16]struct{}
	_ [16 - unsafe.Sizeof(uuid.UUID{})]struct{}
)
