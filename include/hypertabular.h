// This library's version, packed `major << 16 | minor << 8 | patch` from the crate's
// own manifest: the probe every binding makes before its first real call.
//
// # Safety
// None to uphold; `unsafe` only because every export is declared one way.
uint32_t hypertabular_version(void);

// The size of a delimited state block, for a binding that allocates it as bytes. It
// wants 8-byte alignment.
//
// # Safety
// None to uphold.
uintptr_t hypertabular_delimited_state_size(void);

// Starts a delimited input: writes a fresh state to `state` for the dialect at
// `dialect`. [`ERR_CONTRACT`] for a null, a separator the scanner cannot honour, or
// an engine this CPU cannot run.
//
// # Safety
// `state` points to `hypertabular_delimited_state_size()` writable bytes, 8-byte
// aligned; `dialect` to a live `RawDialect`.
int32_t hypertabular_delimited_init(struct HyperTabularDelimitedState *state, const struct HyperTabularRawDialect *dialect);

// Reads the next record as a header. See [`fill::header`].
//
// # Safety
// `state` was initialized by `hypertabular_delimited_init`; `input` is `input_len`
// bytes; `names` has room for `names_cap` spans; `arena` for `arena_cap` bytes;
// `out` is writable.
int32_t hypertabular_delimited_header(struct HyperTabularDelimitedState *state, const uint8_t *input, uintptr_t input_len, uint32_t last, struct HyperTabularSpan *names, uintptr_t names_cap, uint8_t *arena, uintptr_t arena_cap, struct HyperTabularFilled *out);

// Reads up to `max_rows` whole rows into the caller's column buffers. See
// [`fill::fill`].
//
// # Safety
// `state` was initialized by `hypertabular_delimited_init`; `input` is `input_len`
// bytes; `specs` and `columns` are `column_count` entries each, and each column's
// two arrays have room for `max_rows` elements; `buffers` is readable, and its
// `cells` and `arena` hold `cells_cap` spans and `arena_cap` bytes (the rest of it is
// not read); `out` is writable.
//
// The two buffers come in a [`Buffers`] rather than as four arguments of their own,
// as the workbook fill takes them: Mono's interpreter, which runs .NET in the browser
// and in an iOS debug build, passes no more than twelve integer arguments to a native
// function, and this one had thirteen.
int32_t hypertabular_delimited_fill(struct HyperTabularDelimitedState *state, const uint8_t *input, uintptr_t input_len, uint32_t last, const struct HyperTabularColumnSpec *specs, const struct HyperTabularColumnBuffer *columns, uintptr_t column_count, uintptr_t max_rows, const struct HyperTabularBuffers *buffers, struct HyperTabularFilled *out);

// Unescapes one quoted cell — a cell-table entry with its flag set names one — into
// `out`, and returns the bytes written: never more than `len - 1`, and no more than
// `cap`.
//
// # Safety
// `cell` is `len` bytes; `out` has room for `cap`.
uintptr_t hypertabular_delimited_unescape(const uint8_t *cell, uintptr_t len, uint8_t *out, uintptr_t cap);

// The size of a workbook state block, for a binding that allocates it as bytes. It
// wants 8-byte alignment. One block reads one sheet at a time; a block that has been
// opened may be copied, bytes and all, to read another.
//
// # Safety
// None to uphold.
uintptr_t hypertabular_workbook_state_size(void);

// Opens the workbook in `container`: writes a fresh state and says what it found. See
// [`book::open`]. Uses `window` and `arena`.
//
// # Safety
// `state` points to `hypertabular_workbook_state_size()` writable bytes, 8-byte
// aligned; `container` is `container_len` bytes; `buffers` is a live [`Buffers`]
// whose pointers each hold what their sizes say; `out` is writable.
int32_t hypertabular_workbook_open(HyperTabularWorkbookState *state, const uint8_t *container, uintptr_t container_len, const struct HyperTabularBuffers *buffers, struct HyperTabularOpened *out);

// Lists the workbook's sheets. See [`book::sheets`]. Uses `window`, `arena`, `cells`.
//
// # Safety
// `state` was opened by `hypertabular_workbook_open` over these same `container`
// bytes; `buffers` and `out` as there.
int32_t hypertabular_workbook_sheets(HyperTabularWorkbookState *state, const uint8_t *container, uintptr_t container_len, const struct HyperTabularBuffers *buffers, struct HyperTabularFilled *out);

// Loads the workbook's shared strings. See [`book::strings`]. Uses `window`, `arena`,
// `cells`.
//
// # Safety
// As `hypertabular_workbook_sheets`.
int32_t hypertabular_workbook_strings(HyperTabularWorkbookState *state, const uint8_t *container, uintptr_t container_len, const struct HyperTabularBuffers *buffers, struct HyperTabularFilled *out);

// Loads the number-format kind of each cell format. See [`book::styles`]. Uses
// `window`, `arena`, `cells`.
//
// # Safety
// As `hypertabular_workbook_sheets`.
int32_t hypertabular_workbook_styles(HyperTabularWorkbookState *state, const uint8_t *container, uintptr_t container_len, const struct HyperTabularBuffers *buffers, struct HyperTabularFilled *out);

// Positions the state on one sheet: the XLSX part named by the `part_len` bytes at
// `part`, or the ODS or Numbers table at `index` — both as `hypertabular_workbook_sheets`
// listed them. See [`rows::sheet`].
//
// # Safety
// `state` was opened by `hypertabular_workbook_open` over these same `container`
// bytes; `part` is `part_len` bytes; `out` is writable.
int32_t hypertabular_workbook_sheet(HyperTabularWorkbookState *state, const uint8_t *container, uintptr_t container_len, const uint8_t *part, uintptr_t part_len, uint32_t index, uint32_t has_header, uint32_t skip_empty_rows, struct HyperTabularFilled *out);

// Reads the sheet's header row. See [`rows::header`]. Uses `window`, `arena`, `cells`,
// `row`, and the workbook's tables.
//
// # Safety
// `state` was positioned by `hypertabular_workbook_sheet` over these same `container`
// bytes; `buffers` and `out` as for `hypertabular_workbook_open`.
int32_t hypertabular_workbook_header(HyperTabularWorkbookState *state, const uint8_t *container, uintptr_t container_len, const struct HyperTabularBuffers *buffers, struct HyperTabularFilled *out);

// Reads up to `max_rows` rows of the sheet into the caller's column buffers. See
// [`rows::fill`]. Uses every buffer.
//
// # Safety
// `state` was positioned by `hypertabular_workbook_sheet` over these same `container`
// bytes; `specs` and `columns` are `column_count` entries each, and each column's two
// arrays have room for `max_rows` elements; `buffers` and `out` as for
// `hypertabular_workbook_open`.
int32_t hypertabular_workbook_fill(HyperTabularWorkbookState *state, const uint8_t *container, uintptr_t container_len, const struct HyperTabularColumnSpec *specs, const struct HyperTabularColumnBuffer *columns, uintptr_t column_count, uintptr_t max_rows, const struct HyperTabularBuffers *buffers, struct HyperTabularFilled *out);

