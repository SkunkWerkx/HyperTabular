// The C ABI of the hypertabular core (https://github.com/SkunkWerkx/HyperTabular): the 14
// functions the shared and static libraries export, which every binding calls through, and the
// #[repr(C)] types they read and write. hypertabular_version() is the library's version.
//
// Each type is the Rust core's type of the same name behind the HyperTabular prefix, and its
// comments are that type's Rust documentation, so the names in them are Rust's:
// `Failure::COLUMN_COUNT` there is HyperTabularFailure_COLUMN_COUNT here, `ERR_ARENA`
// HYPERTABULAR_ERR_ARENA, the delimited `State` HyperTabularDelimitedState, and `Symbol<8>`
// HyperTabularSymbol_8. The value types a column buffer holds (HyperTabularDecimal,
// HyperTabularTimestamp, HyperTabularDate, HyperTabularCivilDateTime, HyperTabularDuration)
// and the numeric notation a column declares (HyperTabularRawNumFormat) are HyperCast's, the
// layouts this library was built with; HyperCast's own header names the same layouts
// HyperCastDecimal and so on.
//
// The core owns no memory. Every pointer is the caller's for the length of the call and no
// longer; a null where the contract needs memory is HYPERTABULAR_ERR_CONTRACT, and a length of
// 0 never dereferences its pointer. Nothing is kept between calls but what the caller's state
// block holds. Every call returns HYPERTABULAR_OK or one of the HYPERTABULAR_ERR_ codes below;
// none of them is a cell's verdict. A cell that does not cast is a HyperTabularCellVerdict
// beside its value: reason 0 cast, 1 empty, 2 malformed, 3 out of range, HyperCast's codes,
// with the offending span of the cell's own text. A structurally broken input is
// HYPERTABULAR_ERR_STRUCTURE, returned only after every intact row before it was delivered,
// with the result's `failure` saying what and where.
//
// A delimited fill that finds a buffer too small consumes nothing and is simply retried with a
// larger one. A workbook call cannot roll back a deflate stream: on HYPERTABULAR_ERR_WINDOW,
// HYPERTABULAR_ERR_ARENA or HYPERTABULAR_ERR_CELLS it stops in place and reports the size it
// needs, and the caller grows that buffer keeping its contents (a realloc), then repeats the
// call (HyperTabularBuffers says so in full).
//
// A state block is the caller's memory, hypertabular_delimited_state_size() or
// hypertabular_workbook_state_size() bytes, 8-byte aligned. The delimited one is a
// HyperTabularDelimitedState, whose public fields a caller may read; the workbook one is
// opaque.

