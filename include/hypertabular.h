// The memory a workbook call works in — all of it the caller's, handed over again on
// every call — and the delimited fill's `cells` and `arena`. A call uses the buffers its
// own documentation names and ignores the rest (null with a zero size is fine for those).
//
// **Growing a buffer.** A workbook part is a compressed stream, and a read of one cannot
// be rolled back to where the call started the way a read of delimited text can. So when
// a workbook call returns [`ERR_WINDOW`], [`ERR_ARENA`] or [`ERR_CELLS`], nothing is
// undone: the state block holds exactly where the read stopped, as offsets into these
// buffers. The caller makes the buffer the code names at least as large as the result's
// `needed`, **keeping what the old one held** (a `realloc`, or allocate-and-copy), leaves
// every other buffer as it was, and makes the same call again; the read goes on from the
// token it stopped at. Calling again without having grown the buffer returns the same
// code. (Opening a workbook is the one exception: it starts over, and keeps nothing.)
typedef struct HyperTabularBuffers {
  // Where a deflated part is inflated and tokenized: at least 64 KiB. Grown on
  // [`ERR_WINDOW`].
  uint8_t *window;
  // Bytes at `window`.
  uintptr_t window_cap;
  // Text the call produces. Grown on [`ERR_ARENA`].
  uint8_t *arena;
  // Bytes at `arena`.
  uintptr_t arena_cap;
  // Spans the call produces. Grown on [`ERR_CELLS`].
  struct HyperTabularSpan *cells;
  // Spans at `cells`.
  uintptr_t cells_cap;
  // The row being assembled, one [`Slot`] per source column the plan reaches: the
  // widest ordinal in the plan, plus one. Never grown.
  struct HyperTabularSlot *row;
  // Slots at `row`.
  uintptr_t row_cap;
  // The workbook's shared strings as `hypertabular_workbook_strings` wrote them: the
  // bytes, and (in `table`) the span of each. Read, never written.
  const uint8_t *strings;
  // Bytes at `strings`.
  uintptr_t strings_len;
  // The span of each shared string.
  const struct HyperTabularSpan *table;
  // Spans at `table`: how many shared strings there are.
  uintptr_t table_len;
  // The kind of each cell format as `hypertabular_workbook_styles` wrote them. Read.
  const uint8_t *kinds;
  // Bytes at `kinds`: how many cell formats there are.
  uintptr_t kinds_len;
} HyperTabularBuffers;

// What `hypertabular_workbook_open` found.
typedef struct HyperTabularOpened {
  // `1` XLSX, `2` ODS, `3` Numbers.
  uint32_t format;
  // The workbook's date system: HyperCast's `ExcelEpoch` code (`1` 1900, `2` 1904).
  uint32_t epoch;
  // An upper bound on the bytes the shared strings take: the size their part inflates
  // to (Numbers: the size the parts that hold its tables' strings decode to). The
  // directory's figure, held to what the part's compressed bytes can inflate to (1032
  // to one), so a buffer sized by it is never larger than the part could fill. Zero if
  // the workbook has none.
  uint64_t strings_bytes;
  // How many shared strings the part says it has. A hint: the file's word, unchecked;
  // Numbers says nothing, and it is zero.
  uint64_t strings_count;
  // On [`ERR_WINDOW`] or [`ERR_ARENA`], the size that buffer needs.
  uint64_t needed;
  // On [`ERR_STRUCTURE`], what is wrong and where.
  struct HyperTabularFailure failure;
} HyperTabularOpened;
// The layout's size in bytes.
#define HyperTabularOpened_SIZE 64

// An exact decimal — a sign, a 96-bit unsigned magnitude, and a base-10 scale — the
// shape .NET's `decimal` stores natively and Java's `BigDecimal`, Python's `Decimal` and
// Ruby's `BigDecimal` build from directly. The value is `(-1)^negative × (hi·2⁶⁴ + lo) ×
// 10⁻ˢᶜᵃˡᵉ`. Casts produce canonical values: exact trailing fraction zeros are trimmed,
// the scale is minimal, and zero has scale 0 and no negative sign. Casts never round:
// text carrying more nonzero precision than 96 bits and 28 places can hold is
// `OutOfRange`. The public fields also permit directly constructed, noncanonical
// values; display preserves their declared scale and sign without clamping.
// ABI layout: `lo` at offset 0, `hi` at 8, `scale` at 12, `negative` at 13,
// 16 bytes with 8-byte alignment.
typedef struct HyperTabularDecimal {
  // The low 64 bits of the magnitude.
  uint64_t lo;
  // The high 32 bits of the magnitude; the magnitude never exceeds 2⁹⁶ − 1.
  uint32_t hi;
  // Base-10 scale: the number of places the magnitude is shifted right. Casts
  // produce `0..=28`, with no trailing magnitude zeros at a positive scale.
  // This public ABI representation can also be constructed directly; display
  // handles every scale byte without clamping or changing its value.
  uint8_t scale;
  // True for a negative value. Casts never produce a negative zero.
  bool negative;
} HyperTabularDecimal;

// A point in time, independent of any time zone or calendar — protobuf's
// `google.protobuf.Timestamp` layout exactly, so every binding folds it into its platform
// instant type without precision games.
//
// Range: `0001-01-01T00:00:00Z` (seconds -62_135_596_800) through
// `9999-12-31T23:59:59.999999999Z` (seconds 253_402_300_799). `nanos` counts forward from
// `seconds` and is always in `0..=999_999_999`, even for instants before the epoch.
typedef struct HyperTabularTimestamp {
  // Seconds since the Unix epoch `1970-01-01T00:00:00Z`.
  int64_t seconds;
  // Non-negative sub-second nanoseconds, `0..=999_999_999`.
  int32_t nanos;
} HyperTabularTimestamp;

// A calendar date with no time or zone — protobuf's `google.type.Date` field layout.
// Years `1..=9999`, proleptic Gregorian.
typedef struct HyperTabularDate {
  // Year, `1..=9999`.
  uint16_t year;
  // Month, `1..=12`.
  uint8_t month;
  // Day of month, `1..=days_in_month(year, month)`.
  uint8_t day;
} HyperTabularDate;

// A civil (wall-clock) date and time with **no zone** — exactly what zone-less text like
// `1/7/2026 3:04 PM` actually names. Deliberately not a [`Timestamp`]: without a zone
// there is no instant, and inventing one (assuming UTC, say) would be a silent value
// error of up to ±14 hours. Fusing a zone is the caller's job, per the module doctrine.
// ABI layout: the [`Date`] fields at offset 0, `nanos_of_day` at offset 8 (after C
// struct padding).
typedef struct HyperTabularCivilDateTime {
  // The calendar date.
  struct HyperTabularDate date;
  // Nanoseconds since that date's midnight, `0..86_400_000_000_000`.
  uint64_t nanos_of_day;
} HyperTabularCivilDateTime;

// A signed span of time — protobuf's `google.protobuf.Duration` layout exactly.
// `seconds` is bounded to ±315_576_000_000 (±10,000 years); `nanos` carries the same sign
// as `seconds` (unlike [`Timestamp`], whose nanos always count forward).
typedef struct HyperTabularDuration {
  // Whole seconds, `-315_576_000_000..=315_576_000_000`.
  int64_t seconds;
  // Sub-second nanoseconds, `-999_999_999..=999_999_999`, same sign as `seconds`.
  int32_t nanos;
} HyperTabularDuration;

// One sheet as `hypertabular_workbook_sheets` lists it: three spans' worth of the table.
typedef struct HyperTabularSheetInfo {
  // The sheet's name, in the arena.
  struct HyperTabularSpan name;
  // The part that holds it, in the arena: what `hypertabular_workbook_sheet` is given
  // to open it. Empty for ODS and Numbers, where every sheet is reached another way.
  struct HyperTabularSpan part;
  // Bit 0: the sheet is hidden.
  uint32_t flags;
  // The sheet's position among the document's tables (ODS, Numbers), given back
  // likewise.
  uint32_t index;
} HyperTabularSheetInfo;
// The layout's size in bytes.
#define HyperTabularSheetInfo_SIZE 24

