  // The door's code ([`crate::kernel::door::Door::code`]): `1` bool, `2`–`5` i8 to i64,
  // `6`–`9` u8 to u64, `10` f32, `11` f64, `12` UUID, `13` timestamp, `14` Unix time,
  // `15` date, `16` time of day, `17` duration, `18` text, `19` decimal, `20` a date
